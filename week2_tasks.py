# 1. Условия ---------------------------------------------------------------------
def is_even(n: int) -> bool:
    """Вернуть True, если число чётное, иначе False.

    >>> is_even(4)
    True
    >>> is_even(7)
    False

    Подсказка: оператор % даёт остаток от деления.
    """
    return n%2==0


# 2. Условия ---------------------------------------------------------------------
def max_of_three(a: int, b: int, c: int) -> int:
    """Вернуть наибольшее из трёх чисел. Встроенную функцию max() не использовать.

    >>> max_of_three(3, 9, 5)
    9

    Подсказка: if / elif / else и сравнения.
    """
    m = None
    l = [a,b,c]
    for i in l:
        if m is None or i>m:
            m=int(i)
    return m

# 3. Условия ---------------------------------------------------------------------
def grade(score: int) -> str:
    """Перевести балл от 0 до 100 в оценку.

    90–100 → "A", 75–89 → "B", 60–74 → "C", 0–59 → "F".

    >>> grade(95)
    'A'
    >>> grade(60)
    'C'

    Подсказка: цепочка if / elif, проверяй с самого высокого порога.
    """
    if score >= 90: return "A"
    elif 89>=score >= 75: return "B"
    elif 74>=score >= 60: return "C"
    else: return "F"


# 4. Циклы -----------------------------------------------------------------------
def sum_to(n: int) -> int:
    """Вернуть сумму чисел от 1 до n включительно. Для n < 1 вернуть 0.
    Функцию sum() не использовать — нужен цикл.

    >>> sum_to(4)
    10

    Подсказка: переменная-накопитель и цикл for i in range(...).
    Внимательно с границей: range(1, n) не включает n.
    """
    answ = 0
    if n<1: return answ
    else:
        for i in range(1,n+1):
            answ +=i
    return answ


# 5. Циклы и списки --------------------------------------------------------------
def fizzbuzz(n: int) -> list[str]:
    """Вернуть список строк для чисел от 1 до n:
    - если число делится на 3 и на 5 — "FizzBuzz";
    - если только на 3 — "Fizz";
    - если только на 5 — "Buzz";
    - иначе — само число строкой.

    >>> fizzbuzz(5)
    ['1', '2', 'Fizz', '4', 'Buzz']

    Подсказка: пустой список, цикл, .append(), str(i).
    Порядок проверок важен: что будет, если сначала проверить деление на 3?
    """
    answer=[]
    for i in range(1,n+1):
        if i%3==0 and i%5==0: answer.append("FizzBuzz")
        elif i%3==0: answer.append("Fizz")
        elif i%5==0: answer.append("Buzz")
        else: answer.append(str(i))
    return answer


# 6. Строки ----------------------------------------------------------------------
def count_vowels(text: str) -> int:
    """Посчитать гласные латинские буквы a, e, i, o, u в строке, без учёта регистра.

    >>> count_vowels("Hello World")
    3

    Подсказка: цикл по строке (for ch in text), оператор in, метод .lower().
    """
    count = 0
    for i in text.lower():
        if i in 'aeiou': count+=1
    return count


# 7. Строки ----------------------------------------------------------------------
def is_palindrome(text: str) -> bool:
    """Проверить, читается ли строка одинаково в обе стороны.
    Регистр и пробелы не учитываются.

    >>> is_palindrome("А роза упала на лапу Азора")
    True
    >>> is_palindrome("python")
    False

    Подсказка: .lower(), .replace(" ", ""), срез [::-1] разворачивает строку.
    """
    t = text.lower().replace(" ","")
    return t == t[::-1]


# 8. Списки ----------------------------------------------------------------------
def only_positive(nums: list[int]) -> list[int]:
    """Вернуть новый список только из положительных чисел (больше нуля),
    в том же порядке.

    >>> only_positive([3, -1, 0, 5, -7])
    [3, 5]

    Подсказка: цикл + if + .append(). Потом попробуй переписать
    в одну строку через list comprehension: [x for x in nums if ...].
    """
    return [x for x in nums if x>0]

# 9. Списки ----------------------------------------------------------------------
def average(nums: list[float]) -> float:
    """Вернуть среднее арифметическое. Для пустого списка вернуть 0.0.

    >>> average([2, 4, 6])
    4.0

    Подсказка: sum() и len() здесь можно. Подумай, что будет при делении на ноль.
    """
    if len(nums)==0: return 0.0
    return sum(nums)/len(nums)


# 10. Словари --------------------------------------------------------------------
def char_count(text: str) -> dict[str, int]:
    """Посчитать, сколько раз встречается каждый символ. Пробелы не считать.

    >>> char_count("мама")
    {'м': 2, 'а': 2}

    Подсказка: пустой словарь {}, цикл по строке.
    Если символ уже есть в словаре — увеличь счётчик, иначе запиши 1.
    """
    letters={}
    txt = text.replace(" ","")
    for i in txt:
        if i not in letters:
            letters[i]= 1
        else:
            letters[i]+=1
    return letters
